import type { Model } from "schway/host";
import type { StartPayload, Work, WorkGrant } from "./authority-types";
import type { Envelope } from "./types";

/** Owner-granted typed repository identity; its preloaded files exist only in the selected Bot computer. */
export interface CodingRepository {
  id: string;
  revision: number;
  botId: string;
  url: string;
  baseCommit: string;
  active: boolean;
}
/** Exact bounded command and declared network requirement; unsupported egress is refused before execution. */
export interface CodingCheck {
  argv: string[];
  timeoutMs: number;
  network: "none" | "registry";
  coverage: string;
}
/** Atomic coding start captures the existing work grant plus repository and real verification commands. */
export type CodingStartCommand = Envelope<"coding.start", {
  repository: { id: string; revision: number };
  work: StartPayload;
  install: CodingCheck | null;
  tests: CodingCheck[];
}>;
/** Repository grants select an explicit configured resource slot without granting work or credentials. */
export type CodingRepositoryCommand = Envelope<"coding.repository.grant", Omit<CodingRepository, "revision" | "active">> |
  Envelope<"coding.repository.revoke", { repositoryId: string }>;
/** Authenticated coding commands use the common durable receipt boundary. */
export type CodingCommand = CodingStartCommand | CodingRepositoryCommand;
/** Coding receipts retain exact grant identities independently of later execution settlement. */
export interface CodingReceipt {
  kind: CodingCommand["kind"];
  requestId: string;
  repository?: CodingRepository;
  work?: Work;
  grant?: WorkGrant;
}
/** Immutable work binding and command plan; paths and branch names are generated by the service. */
export interface CodingJob {
  workId: string;
  repository: CodingRepository;
  branch: string;
  path: string;
  install: CodingCheck | null;
  tests: CodingCheck[];
}
/** Actual command observations never derive success or coverage from model output. */
export interface CodingCheckResult {
  command: CodingCheck;
  state: "passed" | "failed" | "skipped" | "unknown";
  exitCode: number | null;
  timedOut: boolean;
  reason: string | null;
  stdout: string;
  stderr: string;
}
/** Durable execution status preserves partial evidence and never automatically replays shell work. */
export interface CodingRun {
  attemptId: string;
  workId: string;
  state: "running" | "reviewable" | "partial" | "interrupted";
  reason: string | null;
  baseCommit: string;
  headCommit: string | null;
  diffHash: string | null;
  reportId: string | null;
}
/** Owner query separates retained metadata from currently accessible immutable execution artifacts. */
export interface CodingView {
  job: CodingJob | null;
  runs: CodingRun[];
  available: boolean;
  checks: { attemptId: string; ordinal: number; result: CodingCheckResult }[];
}
/** Deterministic model injection is service-owned and unavailable to HTTP or retrieved repository content. */
export interface CodingOptions { model?: Model }
